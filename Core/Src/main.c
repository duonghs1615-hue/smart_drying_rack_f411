/**
  * @brief  Function implementing the SensorTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartSensorTask */
void StartSensorTask(void *argument)
{
  /* USER CODE BEGIN 5 */
	InputData input;

	  (void)argument;

	  for(;;)
	  {
	    input.rain = Sensor_IsRaining();
	    input.light = Sensor_IsLight();

	    input.mode_button = Button_Mode();
	    input.manual_in = Button_ManualIn();
	    input.manual_out = Button_ManualOut();

	    if(input.rain)
	    {
	      input.environment = ENV_RAIN;
	    }
	    else if(input.light)
	    {
	      input.environment = ENV_BRIGHT;
	    }
	    else
	    {
	      input.environment = ENV_DARK;
	    }

	    osMessageQueuePut(
	        sensorQueueHandle,
	        &input,
	        0U,
	        0U
	    );

	    osDelay(50U);
	  }
  /* USER CODE END 5 */
}

/* USER CODE BEGIN Header_StartControlTask */
/**
* @brief Function implementing the ControlTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartControlTask */
void StartControlTask(void *argument)
{
  /* USER CODE BEGIN StartControlTask */
	  InputData input;
	  SystemState state;
	  SystemState previous_state;
	  uint8_t first_update = 1;
	  (void)argument;

	  state.mode = MODE_AUTO;
	  state.rack = RACK_IN;
	  state.environment = ENV_DARK;

	  previous_state = state;

	  Servo_SetIn();

	  for(;;)
	  {
	    if(osMessageQueueGet(
	        sensorQueueHandle,
	        &input,
	        NULL,
	        osWaitForever) == osOK)
	    {
	      state.environment = input.environment;

	      if(input.mode_button)
	      {
	        state.mode = MODE_MANUAL;
	      }
	      else
	      {
	        state.mode = MODE_AUTO;
	      }

	      if(state.mode == MODE_AUTO)
	      {
	        if(input.rain)
	        {
	          state.rack = RACK_IN;
	        }
	        else if(input.light)
	        {
	          state.rack = RACK_OUT;
	        }
	        else
	        {
	          state.rack = RACK_IN;
	        }
	      }
	      else
	      {
	        if(input.manual_in)
	        {
	          state.rack = RACK_IN;
	        }
	        else if(input.manual_out)
	        {
	          state.rack = RACK_OUT;
	        }
	      }

	      if(state.rack != previous_state.rack)
	      {
	        if(state.rack == RACK_IN)
	        {
	          Servo_SetIn();
	        }
	        else
	        {
	          Servo_SetOut();
	        }
	      }

	      if(first_update ||
	         (state.mode != previous_state.mode) ||
	         (state.rack != previous_state.rack) ||
	         (state.environment != previous_state.environment))
	      {
	        osMessageQueuePut(
	            displayQueueHandle,
	            &state,
	            0U,
	            0U
	        );

	        previous_state = state;
	        first_update = 0U;
	      }
	    }
	  }
  /* USER CODE END StartControlTask */
}


/**
* @brief Function implementing the DisplayTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartDisplayTask */
void StartDisplayTask(void *argument)
{
  /* USER CODE BEGIN StartDisplayTask */
	 SystemState state;

	  (void)argument;

	  UART2_SendString("\r\n");
	  UART2_SendString("============================\r\n");
	  UART2_SendString(" SMART CLOTHES DRYING RACK\r\n");
	  UART2_SendString(" STM32F411 + FREERTOS\r\n");
	  UART2_SendString("============================\r\n");

	  if(osKernelGetState() == osKernelRunning)
	  {
	    UART2_SendString("RTOS KERNEL: RUNNING\r\n");
	  }

	  for(;;)
	  {
	    if(osMessageQueueGet(
	        displayQueueHandle,
	        &state,
	        NULL,
	        osWaitForever) == osOK)
	    {
	      LCD_Update(
	          state.mode,
	          state.rack,
	          state.environment
	      );

	      if(state.mode == MODE_AUTO)
	      {
	        UART2_SendString("MODE: AUTO\r\n");
	      }
	      else
	      {
	        UART2_SendString("MODE: MANUAL\r\n");
	      }

	      if(state.environment == ENV_RAIN)
	      {
	        UART2_SendString("ENVIRONMENT: RAIN\r\n");
	      }
	      else if(state.environment == ENV_BRIGHT)
	      {
	        UART2_SendString("ENVIRONMENT: BRIGHT\r\n");
	      }
	      else
	      {
	        UART2_SendString("ENVIRONMENT: DARK\r\n");
	      }

	      if(state.rack == RACK_IN)
	      {
	        UART2_SendString("RACK: IN\r\n");
	      }
	      else
	      {
	        UART2_SendString("RACK: OUT\r\n");
	      }

	      UART2_SendString("----------------------------\r\n");
	    }
	  }
  /* USER CODE END StartDisplayTask */
}

